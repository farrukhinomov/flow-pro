#!/usr/bin/env node
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const openApiUrl =
  process.env.FLOWPRO_OPENAPI_URL ?? 'http://127.0.0.1:5123/openapi/v1.json'
const outputPath = resolve(
  process.cwd(),
  'src/contracts/generated/openapi.d.ts'
)

function quote(value) {
  return JSON.stringify(value)
}

function getOperations(document) {
  return Object.entries(document.paths ?? {}).flatMap(([path, methods]) =>
    Object.entries(methods ?? {})
      .filter(([method]) =>
        ['get', 'post', 'put', 'patch', 'delete'].includes(method)
      )
      .map(([method, operation]) => ({
        method: method.toUpperCase(),
        operationId: operation.operationId,
        path,
        tag: operation.tags?.[0],
      }))
  )
}

function renderType(document) {
  const operations = getOperations(document)
  const generatedAt = new Date().toISOString()

  return `// Generated by scripts/generate-api-contracts.mjs.
// Source: ${openApiUrl}
// Generated at: ${generatedAt}
// Do not edit this file manually.

export type FlowProApiPath =
${operations.map((operation) => `  | ${quote(operation.path)}`).join('\n') || '  never'}

export type FlowProApiOperation =
${operations
  .map(
    (operation) =>
      `  | { method: ${quote(operation.method)}; path: ${quote(
        operation.path
      )}; operationId: ${quote(operation.operationId ?? '')}; tag: ${quote(
        operation.tag ?? ''
      )} }`
  )
  .join('\n') || '  never'}

export type FlowProApiTag =
${[
  ...new Set(
    operations
      .map((operation) => operation.tag)
      .filter((tag) => typeof tag === 'string' && tag.length > 0)
  ),
]
  .sort()
  .map((tag) => `  | ${quote(tag)}`)
  .join('\n') || '  never'}
`
}

async function main() {
  const response = await fetch(openApiUrl)

  if (!response.ok) {
    throw new Error(
      `Unable to load OpenAPI document from ${openApiUrl}: ${response.status}`
    )
  }

  const document = await response.json()
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, renderType(document))
  console.log(`Generated ${outputPath}`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
