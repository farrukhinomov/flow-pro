function slugify(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function usernameFor(firstName: string, lastName: string) {
  return `${slugify(firstName)}.${slugify(lastName)}`
}

function visibilityScopeFor(role: UserRole) {
  if (role === 'superadmin') return 'Full platform administration'
  if (role === 'admin') return 'Policy and integration administration'
  if (role === 'hr') return 'Request details and audit trail'
  if (role === 'manager') return 'Team planning details'

  return 'Availability only'
}

